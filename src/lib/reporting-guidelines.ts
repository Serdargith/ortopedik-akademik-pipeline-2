export type ReportingGuideline = 'STROBE' | 'CONSORT' | 'PRISMA' | 'CARE' | 'TREND' | 'ROBINS-I' | 'TRIPOD';

export function selectReportingGuideline(studyType: string): ReportingGuideline {
  const lower = studyType.toLowerCase();
  if (lower.includes('randomized') || lower.includes('rct') || lower.includes('trial')) return 'CONSORT';
  if (lower.includes('systematic') || lower.includes('meta-analysis') || lower.includes('review')) return 'PRISMA';
  if (lower.includes('case report') || lower.includes('case series') && lower.includes('single')) return 'CARE';
  if (lower.includes('prediction') || lower.includes('prognostic model') || lower.includes('score')) return 'TRIPOD';
  if (lower.includes('non-random') || lower.includes('quasi')) return 'ROBINS-I';
  return 'STROBE'; // default for observational studies
}

